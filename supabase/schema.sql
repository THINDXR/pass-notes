-- PassNotes schema. Run once in Supabase Dashboard → SQL Editor.
-- All access control lives here (Row Level Security); the client is untrusted.

-- ───────────── Profiles ─────────────
create table profiles (
  id uuid primary key references auth.users on delete cascade,
  username text unique not null check (username ~ '^[a-z0-9_]{3,20}$'),
  display_name text not null check (length(display_name) between 1 and 50)
);
alter table profiles enable row level security;
create policy profiles_read on profiles for select to authenticated using (true);
create policy profiles_insert on profiles for insert to authenticated with check (id = auth.uid());
create policy profiles_update on profiles for update to authenticated using (id = auth.uid());
revoke update on profiles from authenticated;
grant update (display_name) on profiles to authenticated;

-- ───────────── Friends ─────────────
create table friendships (
  requester_id uuid not null references profiles on delete cascade,
  addressee_id uuid not null references profiles on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted')),
  created_at timestamptz not null default now(),
  primary key (requester_id, addressee_id),
  check (requester_id <> addressee_id)
);
-- one row per pair, whichever direction it was sent
create unique index friendships_pair on friendships (least(requester_id, addressee_id), greatest(requester_id, addressee_id));
alter table friendships enable row level security;
create policy friendships_read on friendships for select to authenticated
  using (auth.uid() in (requester_id, addressee_id));
create policy friendships_request on friendships for insert to authenticated
  with check (requester_id = auth.uid() and status = 'pending');
create policy friendships_accept on friendships for update to authenticated
  using (addressee_id = auth.uid()) with check (status = 'accepted');
create policy friendships_remove on friendships for delete to authenticated
  using (auth.uid() in (requester_id, addressee_id));
revoke update on friendships from authenticated;
grant update (status) on friendships to authenticated;

create function are_friends(a uuid, b uuid) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from friendships where status = 'accepted'
    and ((requester_id = a and addressee_id = b) or (requester_id = b and addressee_id = a)))
$$;

-- ───────────── Documents & members ─────────────
create table documents (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null default auth.uid() references profiles on delete cascade,
  title text not null check (length(title) between 1 and 200),
  pdf_path text not null,
  created_at timestamptz not null default now()
);
create table document_members (
  document_id uuid not null references documents on delete cascade,
  user_id uuid not null references profiles on delete cascade,
  role text not null check (role in ('owner', 'editor', 'viewer')),
  primary key (document_id, user_id)
);

-- caller's role on a document, or null. security definer so policies don't recurse.
create function doc_role(doc uuid) returns text
language sql stable security definer set search_path = public as $$
  select role from document_members where document_id = doc and user_id = auth.uid()
$$;

create function add_owner_member() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into document_members values (new.id, new.owner_id, 'owner');
  return new;
end $$;
create trigger documents_owner after insert on documents for each row execute function add_owner_member();

alter table documents enable row level security;
-- owner_id check: RETURNING on insert is checked before the owner-member trigger runs
create policy documents_read on documents for select to authenticated
  using (owner_id = auth.uid() or doc_role(id) is not null);
create policy documents_insert on documents for insert to authenticated
  with check (owner_id = auth.uid() and pdf_path like auth.uid()::text || '/%');
create policy documents_delete on documents for delete to authenticated using (doc_role(id) = 'owner');
revoke update on documents from authenticated;

alter table document_members enable row level security;
create policy members_read on document_members for select to authenticated
  using (doc_role(document_id) is not null);
-- owner removes others; anyone but the owner can leave
create policy members_remove on document_members for delete to authenticated
  using (role <> 'owner' and (user_id = auth.uid() or doc_role(document_id) = 'owner'));
-- members are only added by the trigger above and respond_invite()

-- ───────────── Strokes (the notes) ─────────────
create table strokes (
  id uuid primary key,  -- generated by the client so retries are idempotent
  document_id uuid not null references documents on delete cascade,
  page int not null check (page >= 1),
  author_id uuid not null default auth.uid() references profiles on delete cascade,
  tool text not null check (tool in ('pen', 'highlighter')),
  color text not null check (color ~ '^#[0-9a-fA-F]{6}$'),
  width real not null check (width > 0 and width < 0.2),
  points jsonb not null check (jsonb_typeof(points) = 'array' and jsonb_array_length(points) <= 20000),
  deleted boolean not null default false,
  created_at timestamptz not null default now()
);
create index strokes_doc on strokes (document_id);
alter table strokes enable row level security;
create policy strokes_read on strokes for select to authenticated using (doc_role(document_id) is not null);
create policy strokes_insert on strokes for insert to authenticated
  with check (author_id = auth.uid() and doc_role(document_id) in ('owner', 'editor'));
create policy strokes_erase on strokes for update to authenticated
  using (doc_role(document_id) in ('owner', 'editor'));
revoke update on strokes from authenticated;
grant update (deleted) on strokes to authenticated;  -- erase / undo only flips this flag
alter publication supabase_realtime add table strokes;

-- ───────────── Invites ─────────────
create table invites (
  id uuid primary key default gen_random_uuid(),
  document_id uuid not null references documents on delete cascade,
  title text not null,  -- shown in the recipient's inbox before they can read the document
  from_id uuid not null default auth.uid() references profiles on delete cascade,
  to_id uuid not null references profiles on delete cascade,
  mode text not null check (mode in ('copy', 'collab')),
  role text not null default 'editor' check (role in ('editor', 'viewer')),
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now()
);
alter table invites enable row level security;
create policy invites_read on invites for select to authenticated using (auth.uid() in (from_id, to_id));
create policy invites_send on invites for insert to authenticated
  with check (from_id = auth.uid() and status = 'pending'
    and doc_role(document_id) = 'owner' and are_friends(from_id, to_id));
-- answered only through respond_invite()

-- Accept or decline. Returns the document id to open (the new copy, or the shared doc).
-- shortcut: a copy snapshots notes at accept time, not send time; move the copy into send if that matters.
create function respond_invite(invite_id uuid, accept boolean) returns uuid
language plpgsql security definer set search_path = public as $$
declare
  inv invites;
  doc uuid;
begin
  select * into inv from invites
    where id = invite_id and to_id = auth.uid() and status = 'pending' for update;
  if not found then raise exception 'invite not found'; end if;

  if not accept then
    update invites set status = 'declined' where id = invite_id;
    return null;
  end if;

  if inv.mode = 'collab' then
    insert into document_members values (inv.document_id, auth.uid(), inv.role)
      on conflict (document_id, user_id) do nothing;
    doc := inv.document_id;
  else
    -- the PDF file itself is never modified, so the copy points at the same file
    insert into documents (owner_id, title, pdf_path)
      select auth.uid(), title, pdf_path from documents where id = inv.document_id
      returning id into doc;
    insert into strokes (id, document_id, page, author_id, tool, color, width, points)
      select gen_random_uuid(), doc, page, author_id, tool, color, width, points
      from strokes where document_id = inv.document_id and not deleted;
  end if;

  update invites set status = 'accepted' where id = invite_id;
  return doc;
end $$;
revoke execute on function respond_invite, doc_role, are_friends from anon, public;
grant execute on function respond_invite, doc_role, are_friends to authenticated;

-- ───────────── PDF storage ─────────────
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('pdfs', 'pdfs', false, 52428800, array['application/pdf']);
create policy pdfs_upload on storage.objects for insert to authenticated
  with check (bucket_id = 'pdfs' and (storage.foldername(name))[1] = auth.uid()::text);
-- readable by anyone who can see a document using that file (copies share the file)
create policy pdfs_read on storage.objects for select to authenticated
  using (bucket_id = 'pdfs' and exists (select 1 from documents d where d.pdf_path = storage.objects.name));
-- shortcut: files are not deleted with documents (copies may share them); add a cleanup job if storage grows.
